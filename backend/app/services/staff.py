async def update_staff(session: AsyncSession, workgroup: Workgroup, member: StaffMember, actor: User, data: dict[str, Any]) -> StaffMember:
    changes: list[str] = []
    if "salary_kobo" in data:
        value = data["salary_kobo"]
        if value is not None and value < 0:
            raise ValidationFailed("Salary can't be negative.")
        previous = member.effective_salary_kobo
        member.salary_kobo = value
        changes.append(f"salary {format_naira(previous)} → {format_naira(member.effective_salary_kobo)}")
    if "role_id" in data:
        role_id = data["role_id"]
        if role_id:
            role = await session.get(Role, role_id)
            if role is None or role.workgroup_id != workgroup.id:
                raise NotFound("Role not found.")
            member.role_id = role.id
            member.role = role
            changes.append(f"role → {role.name}")
        else:
            member.role_id = None
            member.role = None
            changes.append("role removed")
    for field_name in ("first_name", "last_name", "email", "phone"):
        if field_name in data:
            setattr(member, field_name, (data[field_name] or "").strip() or None)
            changes.append(field_name.replace("_", " "))
    if "status" in data and data["status"] != member.status:
        new_status = data["status"]
        if new_status == "inactive":
            member.status = "inactive"
            member.deactivated_at = utcnow()
            changes.append("deactivated")
        elif new_status == "active" and member.status == "inactive":
            in_use, remaining = await _capacity(session, workgroup)
            if remaining < 1:
                raise Conflict("No free seats. Increase the staff count to reactivate this staff member.", code="seats_exceeded")
            member.status = "registered" if member.registered_at else "pending"
            member.deactivated_at = None
            changes.append("reactivated")
        else:
            raise ValidationFailed("Status can only be set to active or inactive.")
    if changes:
        audit(
            session,
            action="staff.updated",
            summary=f"{member.display_name or member.staff_code}: {', '.join(changes)}"[:255],
            actor=actor,
            workgroup_id=workgroup.id,
            meta={"staff_id": str(member.id)},
        )
    return member


async def bulk_update(session: AsyncSession, workgroup: Workgroup, actor: User, staff_ids: list[uuid.UUID], data: dict[str, Any]) -> int:
    members = (
        (await session.execute(select(StaffMember).where(StaffMember.workgroup_id == workgroup.id, StaffMember.id.in_(staff_ids))))
        .unique()
        .scalars()
        .all()
    )
    for member in members:
        await update_staff(session, workgroup, member, actor, data)
    return len(members)


async def verify_bank_account(account_number: str, bank_code: str) -> tuple[str, str]:
    account_number = re.sub(r"\D", "", account_number or "")
    if len(account_number) != 10:
        raise ValidationFailed("Account number must be 10 digits.")
    bank = await lookup_bank_name(bank_code)
    if bank is None:
        raise ValidationFailed("Choose a valid bank.")
    try:
        account_name = await get_provider().resolve_account(account_number, bank_code)
    except PaystackError as exc:
        if exc.transient:
            raise AppError("Bank verification is temporarily unavailable. Please try again in a minute.", code="bank_unavailable", status_code=503)
        raise AppError(
            "We couldn't verify that account. Check the account number and bank, then try again.", code="account_unresolved", status_code=422
        )
    return account_name, bank


async def attach_bank(session: AsyncSession, member: StaffMember, account_number: str, bank_code: str) -> StaffMember:
    account_number = re.sub(r"\D", "", account_number or "")
    account_name, bank = await verify_bank_account(account_number, bank_code)
    try:
        recipient = await get_provider().create_recipient(account_name, account_number, bank_code)
    except PaystackError as exc:
        raise AppError(
            "Your account was verified but we couldn't finish setting up payouts. Please try again shortly.",
            code="recipient_failed",
            status_code=503 if exc.transient else 422,
        )
    member.account_number = account_number
    member.bank_code = bank_code
    member.bank_name = bank
    member.account_name = account_name
    member.paystack_recipient_code = recipient
    member.bank_verified_at = utcnow()
    member.name_match = names_match(account_name, member.first_name, member.last_name, member.preset_name)
    return member


async def change_bank(session: AsyncSession, workgroup: Workgroup, member: StaffMember, actor: User, account_number: str, bank_code: str) -> StaffMember:
    if member.status == "pending":
        raise Conflict("This staff ID hasn't been registered yet.")
    await attach_bank(session, member, account_number, bank_code)
    audit(
        session,
        action="staff.bank_changed",
        summary=f"Updated bank details for {member.display_name} ({member.bank_name} ••••{member.account_number[-4:]})",
        actor=actor,
        workgroup_id=workgroup.id,
        meta={"staff_id": str(member.id)},
    )
    return member


async def add_manual(session: AsyncSession, workgroup: Workgroup, actor: User, data: dict[str, Any]) -> StaffMember:
    code = (data.get("staff_code") or "").strip()
    if code:
        if not is_valid_staff_code(code):
            raise ValidationFailed("Staff ID can use letters, numbers, spaces, - _ / . (max 40 characters).")
        if await _existing_norms(session, workgroup.id, [normalise_staff_code(code)]):
            raise Conflict("That staff ID already exists in this workgroup.", code="staff_id_taken")
    in_use, remaining = await _capacity(session, workgroup)
    if remaining < 1:
        raise Conflict("All seats are used. Increase the staff count to add someone.", code="seats_exceeded",
                       details={"headcount": workgroup.headcount, "in_use": in_use, "remaining": 0, "requested": 1})
    if not code:
        while True:
            code = generate_staff_code(workgroup.staff_id_prefix)
            if not (await session.execute(select(StaffMember.id).where(StaffMember.staff_code_norm == code))).first():
                break
    member = StaffMember(
        workgroup_id=workgroup.id,
        staff_code=code,
        staff_code_norm=normalise_staff_code(code),
        source="manual",
        status="registered",
        first_name=data["first_name"].strip(),
        last_name=data["last_name"].strip(),
        email=(data.get("email") or "").strip().lower() or None,
        phone=(data.get("phone") or "").strip() or None,
        salary_kobo=data.get("salary_kobo"),
        role_id=data.get("role_id"),
    )
    if member.role_id:
        role = await session.get(Role, member.role_id)
        if role is None or role.workgroup_id != workgroup.id:
            raise NotFound("Role not found.")
        member.role = role
    await attach_bank(session, member, data["account_number"], data["bank_code"])
    member.registered_at = utcnow()
    session.add(member)
    await session.flush()
    audit(session, action="staff.added", summary=f"Added {member.display_name} ({member.staff_code}) manually", actor=actor, workgroup_id=workgroup.id)
    return member


async def reset_registration(session: AsyncSession, workgroup: Workgroup, member: StaffMember, actor: User) -> StaffMember:
    if member.status != "registered":
        raise Conflict("Only registered staff can be reset.")
    member.status = "pending"
    member.first_name = member.last_name = None
    member.account_number = member.account_name = member.bank_code = member.bank_name = None
    member.paystack_recipient_code = None
    member.bank_verified_at = None
    member.name_match = None
    member.registered_at = None
    member.registration_ip = None
    audit(session, action="staff.reset", summary=f"Reset registration for staff ID {member.staff_code}", actor=actor, workgroup_id=workgroup.id)
    return member


async def delete_staff(session: AsyncSession, workgroup: Workgroup, member: StaffMember, actor: User) -> str:
    """Deletes unused IDs; staff with payment history are deactivated instead."""
    has_history = (await session.execute(select(PayrollItem.id).where(PayrollItem.staff_id == member.id).limit(1))).first() is not None
    if has_history:
        member.status = "inactive"
        member.deactivated_at = utcnow()
        audit(session, action="staff.deactivated", summary=f"Deactivated {member.display_name or member.staff_code}", actor=actor, workgroup_id=workgroup.id)
        return "deactivated"
    label = member.display_name or member.staff_code
    await session.delete(member)
    audit(session, action="staff.deleted", summary=f"Deleted staff ID {member.staff_code} ({label})", actor=actor, workgroup_id=workgroup.id)
    return "deleted"


async def delete_unclaimed(session: AsyncSession, workgroup: Workgroup, actor: User, staff_ids: list[uuid.UUID] | None) -> int:
    stmt = select(StaffMember).where(StaffMember.workgroup_id == workgroup.id, StaffMember.status == "pending")
    if staff_ids:
        stmt = stmt.where(StaffMember.id.in_(staff_ids))
    members = (await session.execute(stmt)).unique().scalars().all()
    for member in members:
        await session.delete(member)
    if members:
        audit(session, action="staff_ids.deleted", summary=f"Deleted {len(members)} unclaimed staff ID(s)", actor=actor, workgroup_id=workgroup.id)
    return len(members)


