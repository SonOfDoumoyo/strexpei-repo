async def export_rows(session: AsyncSession, workgroup_id: uuid.UUID, only_ids: bool) -> tuple[list[str], list[list[Any]]]:
    members = (
        (
            await session.execute(
                select(StaffMember).where(StaffMember.workgroup_id == workgroup_id).order_by(StaffMember.status, StaffMember.staff_code)
            )
        )
        .unique()
        .scalars()
        .all()
    )
    if only_ids:
        header = ["Staff ID", "Status", "Name on file", "Registered name", "Source"]
        rows = [[m.staff_code, m.status, m.preset_name or "", m.display_name if m.registered_at else "", m.source] for m in members]
        return header, rows
    header = ["Staff ID", "Status", "First name", "Last name", "Email", "Phone", "Role", "Monthly salary (NGN)", "Bank", "Account number",
              "Account name", "Name matches bank", "Registered at"]
    rows = []
    for m in members:
        rows.append([
            m.staff_code, m.status, m.first_name or "", m.last_name or "", m.email or "", m.phone or "",
            m.role.name if m.role else "", f"{m.effective_salary_kobo / 100:.2f}", m.bank_name or "",
            m.account_number or "", m.account_name or "",
            "" if m.name_match is None else ("yes" if m.name_match else "no"),
            m.registered_at.strftime("%Y-%m-%d %H:%M") if m.registered_at else "",
        ])
    return header, rows


def to_csv(header: list[str], rows: list[list[Any]]) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(header)
    for row in rows:
        # Neutralise spreadsheet formula injection.
        writer.writerow([("'" + c) if isinstance(c, str) and c[:1] in ("=", "+", "-", "@") else c for c in row])
    return ("﻿" + buffer.getvalue()).encode("utf-8")


def to_xlsx(header: list[str], rows: list[list[Any]], title: str) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = title[:31] or "Sheet1"
    sheet.append(header)
    for cell in sheet[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="151412")
    for row in rows:
        sheet.append([("'" + c) if isinstance(c, str) and c[:1] in ("=", "+", "-", "@") else c for c in row])
    for index, column in enumerate(sheet.columns, start=1):
        width = max(len(str(c.value or "")) for c in column)
        sheet.column_dimensions[column[0].column_letter].width = min(48, max(12, width + 2))
    sheet.freeze_panes = "A2"
    buffer = io.BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()
