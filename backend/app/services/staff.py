MAX_UPLOAD_ROWS = 5000

HEADER_ALIASES = {
    "staff_code": {"staff id", "staffid", "staff_id", "id", "employee id", "employee_id", "employee no", "employee number", "staff no",
                   "staff number", "code", "staff code", "emp id", "emp no", "payroll id"},
    "first_name": {"first name", "firstname", "first_name", "given name"},
    "last_name": {"last name", "lastname", "last_name", "surname", "family name"},
    "full_name": {"name", "full name", "fullname", "full_name", "staff name", "employee name"},
    "email": {"email", "email address", "e-mail"},
    "phone": {"phone", "phone number", "mobile", "telephone"},
    "role": {"role", "position", "title", "job title", "grade", "designation"},
    "salary": {"salary", "monthly salary", "net pay", "net salary", "amount", "pay"},
}


# ---------------------------------------------------------------- helpers
def _norm_header(value: Any) -> str:
    return re.sub(r"[\s_\-]+", " ", str(value or "").strip().lower())


def _header_map(row: list[Any]) -> dict[str, int] | None:
    mapping: dict[str, int] = {}
    for index, cell in enumerate(row):
        name = _norm_header(cell)
        for key, aliases in HEADER_ALIASES.items():
            if name in {a.replace("_", " ") for a in aliases} and key not in mapping:
                mapping[key] = index
    return mapping if "staff_code" in mapping else None


@dataclass
class ParsedRow:
    staff_code: str
    line: int
    full_name: str | None = None
    first_name: str | None = None
    last_name: str | None = None
    email: str | None = None
    phone: str | None = None
    role: str | None = None
    salary_kobo: int | None = None


@dataclass
class UploadReport:
    added: list[str] = field(default_factory=list)
    duplicates_in_file: list[str] = field(default_factory=list)
    already_exists: list[str] = field(default_factory=list)
    invalid: list[dict[str, Any]] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "added_count": len(self.added),
            "added": self.added[:50],
            "duplicates_in_file": self.duplicates_in_file[:50],
            "already_exists": self.already_exists[:50],
            "invalid": self.invalid[:50],
            "skipped_count": len(self.duplicates_in_file) + len(self.already_exists) + len(self.invalid),
        }


def _rows_from_table(table: list[list[Any]]) -> tuple[list[ParsedRow], list[dict[str, Any]]]:
    table = [row for row in table if any(str(c or "").strip() for c in row)]
    if not table:
        return [], []
    header = _header_map(table[0])
    body = table[1:] if header else table
    start_line = 2 if header else 1
    rows: list[ParsedRow] = []
    invalid: list[dict[str, Any]] = []

    def cell(row: list[Any], key: str) -> str | None:
        if not header or key not in header or header[key] >= len(row):
            return None
        value = row[header[key]]
        if value is None:
            return None
        if isinstance(value, float) and value.is_integer():
            value = int(value)
        text = str(value).strip()
        return text or None

    for offset, row in enumerate(body):
        line = start_line + offset
        if header:
            code = cell(row, "staff_code")
        else:
            first = row[0] if row else None
            if isinstance(first, float) and first.is_integer():
                first = int(first)
            code = str(first).strip() if first is not None else None
        if not code:
            invalid.append({"line": line, "value": "", "reason": "Missing staff ID"})
            continue
        if not is_valid_staff_code(code):
            invalid.append({"line": line, "value": code[:40], "reason": "Use letters, numbers, spaces, - _ / . (max 40 characters)"})
            continue
        parsed = ParsedRow(staff_code=re.sub(r"\s+", " ", code.strip()), line=line)
        if header:
            parsed.first_name = cell(row, "first_name")
            parsed.last_name = cell(row, "last_name")
            parsed.full_name = cell(row, "full_name")
            parsed.email = cell(row, "email")
            parsed.phone = cell(row, "phone")
            parsed.role = cell(row, "role")
            salary = cell(row, "salary")
            if salary:
                try:
                    parsed.salary_kobo = naira_to_kobo(salary)
                    if parsed.salary_kobo < 0:
                        raise ValueError
                except ValueError:
                    invalid.append({"line": line, "value": salary, "reason": "Salary is not a valid amount"})
                    continue
        rows.append(parsed)
    if len(rows) + len(invalid) > MAX_UPLOAD_ROWS:
        raise ValidationFailed(f"Upload at most {MAX_UPLOAD_ROWS:,} staff at a time.")
    return rows, invalid


def parse_upload(filename: str, content: bytes) -> tuple[list[ParsedRow], list[dict[str, Any]]]:
    name = (filename or "").lower()
    if name.endswith((".xlsx", ".xlsm")):
        from openpyxl import load_workbook

        try:
            workbook = load_workbook(io.BytesIO(content), read_only=True, data_only=True)
        except Exception as exc:
            raise ValidationFailed("We couldn't read that Excel file. Save it as .xlsx or .csv and try again.") from exc
        sheet = workbook.worksheets[0]
        table = [list(row) for row in sheet.iter_rows(values_only=True, max_row=MAX_UPLOAD_ROWS + 2)]
        workbook.close()
        return _rows_from_table(table)
    if name.endswith(".xls"):
        raise ValidationFailed("Old .xls files aren't supported. Save the sheet as .xlsx or .csv.")
    try:
        text = content.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = content.decode("latin-1")
    if name.endswith(".csv") or ("," in text and "\n" in text):
        try:
            dialect = csv.Sniffer().sniff(text[:2048], delimiters=",;\t")
        except csv.Error:
            dialect = csv.excel
        table = [row for row in csv.reader(io.StringIO(text), dialect)]
        return _rows_from_table(table)
    return parse_pasted(text)


def parse_pasted(text: str) -> tuple[list[ParsedRow], list[dict[str, Any]]]:
    tokens = [t for t in re.split(r"[\n,;\t]+", text) if t.strip()]
    return _rows_from_table([[t] for t in tokens])


# ------------------------------------------------------------- creation
async def _existing_norms(session: AsyncSession, workgroup_id: uuid.UUID, norms: list[str]) -> set[str]:
    found: set[str] = set()
    for i in range(0, len(norms), 1000):
        chunk = norms[i : i + 1000]
        result = await session.execute(
            select(StaffMember.staff_code_norm).where(StaffMember.workgroup_id == workgroup_id, StaffMember.staff_code_norm.in_(chunk))
        )
        found.update(result.scalars().all())
    return found


async def _capacity(session: AsyncSession, workgroup: Workgroup) -> tuple[int, int]:
    in_use = await billing.seats_in_use(session, workgroup.id)
    return in_use, max(0, workgroup.headcount - in_use)


async def generate_ids(session: AsyncSession, workgroup: Workgroup, count: int, actor: User | None) -> list[StaffMember]:
    if count < 1:
        raise ValidationFailed("Generate at least one staff ID.")
    in_use, remaining = await _capacity(session, workgroup)
    if count > remaining:
        raise Conflict(
            f"This workgroup has {workgroup.headcount} seats and {in_use} are already used. "
            f"Increase the staff count to generate {count} more ID(s).",
            code="seats_exceeded",
            details={"headcount": workgroup.headcount, "in_use": in_use, "remaining": remaining, "requested": count},
        )
    created: list[StaffMember] = []
    pending_codes: set[str] = set()
    while len(pending_codes) < count:
        batch = {generate_staff_code(workgroup.staff_id_prefix) for _ in range(count - len(pending_codes))}
        batch -= pending_codes
        # Generated IDs are unique across the whole platform, not only this workgroup.
        taken = set(
            (await session.execute(select(StaffMember.staff_code_norm).where(StaffMember.staff_code_norm.in_(list(batch))))).scalars().all()
        )
        pending_codes |= batch - taken
    for code in sorted(pending_codes):
        member = StaffMember(workgroup_id=workgroup.id, staff_code=code, staff_code_norm=normalise_staff_code(code), source="generated", status="pending")
        session.add(member)
        created.append(member)
    await session.flush()
    audit(session, action="staff_ids.generated", summary=f"Generated {count} staff ID(s)", actor=actor, workgroup_id=workgroup.id, meta={"count": count})
    return created


async def import_ids(session: AsyncSession, workgroup: Workgroup, rows: list[ParsedRow], invalid: list[dict[str, Any]], actor: User | None, source: str = "uploaded") -> UploadReport:
    report = UploadReport(invalid=list(invalid))
    seen: set[str] = set()
    unique_rows: list[ParsedRow] = []
    for row in rows:
        norm = normalise_staff_code(row.staff_code)
        if norm in seen:
            report.duplicates_in_file.append(row.staff_code)
            continue
        seen.add(norm)
        unique_rows.append(row)
    existing = await _existing_norms(session, workgroup.id, [normalise_staff_code(r.staff_code) for r in unique_rows])
    to_add = []
    for row in unique_rows:
        if normalise_staff_code(row.staff_code) in existing:
            report.already_exists.append(row.staff_code)
        else:
            to_add.append(row)
    if not to_add:
        return report
    in_use, remaining = await _capacity(session, workgroup)
    if len(to_add) > remaining:
        raise Conflict(
            f"This file has {len(to_add)} new staff IDs but only {remaining} of {workgroup.headcount} seats are free. "
            "Increase the staff count for this workgroup first.",
            code="seats_exceeded",
            details={"headcount": workgroup.headcount, "in_use": in_use, "remaining": remaining, "requested": len(to_add)},
        )
    roles_by_name: dict[str, Role] = {}
    role_names = {r.role.strip() for r in to_add if r.role}
    if role_names:
        for role in (await session.execute(select(Role).where(Role.workgroup_id == workgroup.id))).scalars().all():
            roles_by_name[role.name_norm] = role
        for name in role_names:
            norm = name.lower()
            if norm not in roles_by_name:
                role = Role(workgroup_id=workgroup.id, name=name[:80], name_norm=norm[:80], salary_kobo=0)
                session.add(role)
                roles_by_name[norm] = role
        await session.flush()
    for row in to_add:
        full_name = row.full_name or " ".join(p for p in (row.first_name, row.last_name) if p) or None
        member = StaffMember(
            workgroup_id=workgroup.id,
            staff_code=row.staff_code,
            staff_code_norm=normalise_staff_code(row.staff_code),
            source=source,
            status="pending",
            preset_name=full_name[:160] if full_name else None,
            email=(row.email or None),
            phone=(row.phone or None),
            salary_kobo=row.salary_kobo,
            role_id=roles_by_name[row.role.strip().lower()].id if row.role else None,
        )
        session.add(member)
        report.added.append(row.staff_code)
    await session.flush()
    audit(
        session,
        action="staff_ids.imported",
        summary=f"Imported {len(report.added)} staff ID(s)",
        actor=actor,
        workgroup_id=workgroup.id,
        meta={"added": len(report.added), "skipped": report.as_dict()["skipped_count"]},
    )
    return report


# ---------------------------------------------------------------- queries
async def list_staff(
    session: AsyncSession,
    workgroup_id: uuid.UUID,
    *,
    status: str | None = None,
    query: str | None = None,
    role_id: uuid.UUID | None = None,
    attention: bool = False,
    page: int = 1,
    page_size: int = 50,
) -> tuple[list[StaffMember], int]:
    stmt = select(StaffMember).where(StaffMember.workgroup_id == workgroup_id)
    if status:
        stmt = stmt.where(StaffMember.status == status)
    if role_id:
        stmt = stmt.where(StaffMember.role_id == role_id)
    if query:
        like = f"%{query.strip().lower()}%"
        stmt = stmt.where(
            or_(
                func.lower(StaffMember.staff_code).like(like),
                func.lower(func.coalesce(StaffMember.first_name, "")).like(like),
                func.lower(func.coalesce(StaffMember.last_name, "")).like(like),
                func.lower(func.coalesce(StaffMember.preset_name, "")).like(like),
                func.lower(func.coalesce(StaffMember.email, "")).like(like),
                func.coalesce(StaffMember.account_number, "").like(like),
                func.lower(func.coalesce(StaffMember.first_name, "") + " " + func.coalesce(StaffMember.last_name, "")).like(like),
            )
        )
    if attention:
        stmt = stmt.where(StaffMember.status == "registered").where(
            or_(StaffMember.name_match.is_(False), StaffMember.paystack_recipient_code.is_(None))
        )
    total = (await session.execute(select(func.count()).select_from(stmt.subquery()))).scalar_one()
    status_order = case((StaffMember.status == "registered", 0), (StaffMember.status == "pending", 1), else_=2)
    stmt = stmt.order_by(status_order, func.lower(func.coalesce(StaffMember.first_name, StaffMember.preset_name, StaffMember.staff_code)), StaffMember.staff_code)
    stmt = stmt.offset((page - 1) * page_size).limit(page_size)
    items = list((await session.execute(stmt)).unique().scalars().all())
    return items, int(total)


async def get_staff(session: AsyncSession, workgroup_id: uuid.UUID, staff_id: uuid.UUID) -> StaffMember:
    member = await session.get(StaffMember, staff_id)
    if member is None or member.workgroup_id != workgroup_id:
        raise NotFound("Staff member not found.")
    return member


async def find_staff(session: AsyncSession, workgroup_id: uuid.UUID, needle: str) -> list[StaffMember]:
    """By staff ID (exact) or name (fuzzy) — used by the assistant."""
    norm = normalise_staff_code(needle)
    exact = (
        (await session.execute(select(StaffMember).where(StaffMember.workgroup_id == workgroup_id, StaffMember.staff_code_norm == norm)))
        .unique()
        .scalars()
        .all()
    )
    if exact:
        return list(exact)
    items, _ = await list_staff(session, workgroup_id, query=needle, page_size=10)
    return items


